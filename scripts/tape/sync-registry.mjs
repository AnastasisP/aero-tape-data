// Pins the v3 address registry to one upstream commit.
//   node scripts/tape/sync-registry.mjs <commit-sha>
// Fetches every deployment-addresses/*.json at that commit and writes
// lib/data/aero-v3/registry/deployments.json (addresses + sha256 of each raw file).
// Fails, and writes nothing, if a file names a chain that chains.json does not know.
import { writeFileSync } from "node:fs";
import {
  DEPLOYMENTS_PATH,
  UPSTREAM_DIR,
  UPSTREAM_REPO,
  addressEntries,
  fetchJson,
  fetchText,
  loadChains,
  parseFileName,
  rawUrl,
  sha256,
} from "./registry-lib.mjs";

const commit = process.argv[2];
if (!commit || !/^[0-9a-f]{40}$/.test(commit)) {
  console.error("usage: node scripts/tape/sync-registry.mjs <40-hex commit sha>");
  process.exit(2);
}

const slugs = new Set(loadChains().map((c) => c.slug));
const listing = await fetchJson(
  `https://api.github.com/repos/${UPSTREAM_REPO}/contents/${UPSTREAM_DIR}?ref=${commit}`,
);
const names = listing
  .filter((e) => e.type === "file" && e.name.endsWith(".json"))
  .map((e) => e.name)
  .sort();

const files = {};
for (const name of names) {
  const { group, slug } = parseFileName(name);
  if (!slugs.has(slug)) throw new Error(`${name}: chain "${slug}" is not in chains.json`);
  const raw = await fetchText(rawUrl(commit, name));
  files[name] = {
    chain: slug,
    group,
    sha256: sha256(raw),
    addresses: Object.fromEntries(addressEntries(JSON.parse(raw))),
  };
}

const out = {
  _comment: "GENERATED by scripts/tape/sync-registry.mjs. Do not edit by hand. Verify with pnpm tape:verify-registry.",
  source: { repo: UPSTREAM_REPO, dir: UPSTREAM_DIR, commit },
  files,
};
writeFileSync(DEPLOYMENTS_PATH, JSON.stringify(out, null, 2) + "\n");
const count = Object.values(files).reduce((n, f) => n + Object.keys(f.addresses).length, 0);
console.log(`wrote ${names.length} files, ${count} addresses @ ${commit}`);
